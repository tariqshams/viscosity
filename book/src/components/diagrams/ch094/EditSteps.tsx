import { StepFrame, useSteps, CodeTrace } from '../../viz/stepper';
import { Box, Svg, T, tok } from '../../viz/svg';

// The real edit list emit.ts builds for this program (start, end, new
// text), already sorted back to front, applied one at a time.
const SRC = `const ps = [];
for (let i = 0; i < 100; i++)
  ps.push({ x: i, vx: 1 });
for (const p of ps) p.x += p.vx;
`;
type Edit = { start: number; end: number; text: string; line: number };
const EDITS: Edit[] = [
  { start: 100, end: 104, text: 'ps.vx[p]', line: 3 },
  { start: 93, end: 96, text: 'ps.x[p]', line: 3 },
  { start: 78, end: 91, text: 'let p = 0; p < ps.length; p++', line: 3 },
  { start: 55, end: 70, text: 'i, 1', line: 2 },
  { start: 11, end: 13, text: 'new __Vsc_ps()', line: 0 },
];
const PRELUDE = '// Generated by Viscosity: …\nclass __Vsc_ps { … }\n';

const texts: string[] = [SRC];
for (const e of EDITS) {
  const t = texts[texts.length - 1];
  texts.push(t.slice(0, e.start) + e.text + t.slice(e.end));
}

type S = { applied: number; cur: number | null; prelude: boolean; overlap: boolean; note: string };
const STATES: S[] = [
  { applied: 0, cur: null, prelude: false, overlap: false, note: 'The plan says ps becomes a struct of arrays. The emitter collects five edits, each a source range and its replacement text, then sorts them by start offset, last first. Everything outside the ranges will be copied untouched.' },
  ...EDITS.map((e, k) => ({
    applied: k + 1, cur: k, prelude: false, overlap: false,
    note: [
      'Edit 1, offsets 100–104: p.vx becomes ps.vx[p]. The new text is longer, which shifts everything after it, but nothing after it is left to edit.',
      'Edit 2, offsets 93–96: p.x becomes ps.x[p]. Offsets 93 and 96 still point at p.x, because the only change so far lies further right.',
      'Edit 3, offsets 78–91: the for-of header becomes an index loop. p now holds an index, which is why the field edits wrote ps.x[p].',
      'Edit 4, offsets 55–70: push({ x: i, vx: 1 }) becomes push(i, 1), the field values in column order.',
      'Edit 5, offsets 11–13: the empty array becomes new __Vsc_ps(). Applied front to back, this would have shifted every later offset by 12.',
    ][k],
  })),
  { applied: 5, cur: null, prelude: true, overlap: false, note: 'Last, the prelude (the generated container class) goes at the top: after a shebang or a "use strict" directive if there is one, here at offset 0.' },
  { applied: 0, cur: null, prelude: false, overlap: true, note: 'Without the field-edit dedupe, p.x += … would produce two edits for 93–96, one for the read and one for the write. Sorted, the second ends after the first starts, so the emitter throws "internal error: overlapping rewrites at 93-96" instead of writing broken code.' },
];

const X0 = 16;
const W = 368;
const px = (o: number) => X0 + (o / SRC.length) * W;
const LINES = [0, 15, 45, 73];

export default function EditSteps() {
  const s = useSteps(STATES);
  const st = s.state;
  const text = st.overlap ? SRC : (st.prelude ? PRELUDE : '') + texts[st.applied];
  const line = st.cur === null ? null : EDITS[st.cur].line + (st.prelude ? 2 : 0);
  return (
    <StepFrame title="Applying edits back to front" steps={s} note={st.note}>
      <Svg w={400} h={96} title="The source as a ruler of character offsets, with the five edited ranges marked">
        <T x={X0} y={10} size={10} fill={tok('muted')}>offset 0</T>
        <T x={X0 + W} y={10} size={10} anchor="end" fill={tok('muted')}>{SRC.length}</T>
        <line x1={X0} y1={42} x2={X0 + W} y2={42} stroke={tok('line')} strokeWidth={2} />
        {LINES.map((o, k) => (
          <g key={o}>
            <line x1={px(o)} y1={30} x2={px(o)} y2={54} stroke={tok('muted')} strokeWidth={1} />
            <T x={px(o) + 3} y={24} size={9} fill={tok('muted')}>{`line ${k + 1}`}</T>
          </g>
        ))}
        {EDITS.map((e, k) => {
          const done = !st.overlap && k < st.applied;
          const on = st.cur === k || (st.overlap && k === 1);
          const bad = st.overlap && k === 1;
          return (
            <g key={k}>
              <Box x={px(e.start)} y={34} w={Math.max(6, px(e.end) - px(e.start))} h={16} r={2}
                fill={bad ? tok('danger', 0.35) : on ? tok('brand', 0.5) : done ? tok('safe', 0.25) : tok('ink', 0.12)}
                stroke={bad ? tok('danger') : on ? tok('brand') : tok('ink', 0.4)} />
              <T x={(px(e.start) + px(e.end)) / 2} y={66} size={10} mono anchor="middle"
                fill={on ? tok('brand') : tok('muted')}>{String(k + 1)}</T>
            </g>
          );
        })}
        {st.overlap && (
          <g>
            <Box x={px(93) - 3} y={30} w={px(96) - px(93) + 6} h={24} r={2} fill="transparent" stroke={tok('danger')} dash />
            <T x={200} y={86} size={11} anchor="middle" fill={tok('danger')} weight={700}>two edits for 93–96: overlap, throw</T>
          </g>
        )}
        {!st.overlap && (
          <T x={200} y={86} size={11} anchor="middle" fill={tok('muted')}>
            {st.applied === 0 ? 'applied in order 1 → 5 (right to left)' : `${st.applied} of 5 applied`}
          </T>
        )}
      </Svg>
      <div className="mt-2 overflow-x-auto text-[0.8rem]">
        <CodeTrace code={text.replace(/\n$/, '')} line={line} />
      </div>
    </StepFrame>
  );
}

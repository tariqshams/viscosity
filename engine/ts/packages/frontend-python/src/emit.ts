// Emitting Python with column storage (book chapter 116). Like the JS
// emitter, it only replaces the source ranges it must.
//
//   ps = []                         ->  ps = _Vsc_ps()
//   ps.append(P(a, b))              ->  ps.append(a, b)
//   ps[i].x                         ->  ps.x[i]
//   p = ps[i]; p.x                  ->  p = i; ps.x[p]
//   for p in ps:                    ->  for p in _vsc_iter(ps):
//
// Columns are array('d') for fields proven to always hold floats, and plain
// lists otherwise. In Python an int stored in array('d') would come back as a
// float and print as "1.0", so ints never go into typed columns.
import type { CollectionPlan, Plan } from '../../core/src/plan.ts';
import type { Inst } from '../../core/src/vir.ts';
import type { PyLowered } from './lower.ts';
import type { PyNode } from './parser.ts';

interface Edit { start: number; end: number; text: string; write?: boolean }

const RESERVED = new Set(['n', 'append', '_of', '__len__', '__init__', '__slots__']);
const col = (f: string, i: number) => (RESERVED.has(f) || f.startsWith('__') ? `f${i}_` : f);

function containerClass(cp: CollectionPlan): string {
  const c = cp.collection;
  const cols = c.fields.map(col);
  const lines = [
    `# Generated by Viscosity: "${c.name}" stored as a struct of arrays (fields ${c.fields.join(', ')}).`,
    `class _Vsc_${c.name}:`,
    `    __slots__ = ('n', ${cols.map((n) => `'${n}'`).join(', ')}${cols.length === 0 ? '' : ''})`,
    `    def __init__(self):`,
    `        self.n = 0`,
    ...cols.map((n, k) => `        self.${n} = ${c.numericFields.has(c.fields[k]) ? "_vsc_array('d')" : '[]'}`),
    `    def append(self, ${cols.map((_, k) => `v${k}`).join(', ')}):`,
    ...cols.map((n, k) => `        self.${n}.append(v${k})`),
    `        self.n += 1`,
    `    def __len__(self):`,
    `        return self.n`,
    `    @classmethod`,
    `    def _of(cls, *v):`,
    `        c = cls()`,
    `        for i in range(0, len(v), ${c.fields.length}):`,
    `            c.append(${c.fields.map((_, k) => `v[i + ${k}]`).join(', ')})`,
    `        return c`,
  ];
  return lines.join('\n');
}

const HELPERS = `from array import array as _vsc_array
# Generated by Viscosity: bounds check matching list's IndexError.
def _vsc_ix(c, i):
    if -c.n <= i < c.n:
        return i
    raise IndexError('list index out of range')
# Generated by Viscosity: like iterating a list, re-checks the length each step.
def _vsc_iter(c):
    i = 0
    while i < c.n:
        yield i
        i += 1
`;

export function emitPython(source: string, low: PyLowered, p: Plan): string {
  const edits: Edit[] = [];
  const classes: string[] = [];
  const text = (n: PyNode) => source.slice(n.start, n.end);
  const nodeOf = (i: Inst) => i.src!.node as PyNode;
  const fieldEdits = new Map<string, Edit>();

  for (const cp of p.collections) {
    if (cp.layout === 'aos') continue;
    if (cp.layout === 'aosoa') throw new Error('AoSoA is not supported for Python');
    const c = cp.collection;
    const cls = `_Vsc_${c.name}`;
    classes.push(containerClass(cp));
    const recordArgs = (r: Inst): string => {
      const call = nodeOf(r);
      const dc = low.recordClass.get(r.id)!;
      const vals: string[] = call.args.map((a: PyNode) => text(a));
      const rest = dc.fields.slice(call.args.length);
      let k = 0;
      for (const f of rest) {
        if (k < call.keywords.length && call.keywords[k].arg === f) vals.push(text(call.keywords[k++].value));
        else vals.push(text(dc.defaults[dc.fields.indexOf(f)]!));
      }
      return vals.join(', ');
    };

    const init = nodeOf(c.init);
    edits.push({ start: init.start, end: init.end, text: c.init.op === 'array.empty' ? `${cls}()` : `${cls}._of(${c.initRecords.map(recordArgs).join(', ')})` });
    for (const pu of c.pushes) {
      const r = low.module.values[pu.args[1]];
      const rn = nodeOf(r);
      edits.push({ start: rn.start, end: rn.end, text: recordArgs(r) });
    }

    const info = new Map<Inst, { arr: string; idx: string; direct: boolean }>();
    const proven = new Map(c.indexGets.map((g) => [g.inst, g.boundsProven]));
    for (const g of c.indexGets) {
      const n = nodeOf(g.inst);
      if (n.type === 'For') {
        edits.push({ start: n.iter.start, end: n.iter.end, text: `_vsc_iter(${text(n.iter)})` });
        info.set(g.inst, { arr: text(n.iter), idx: n.target.id, direct: false });
        continue;
      }
      const par = low.parent.get(n);
      const direct = !!par && par.type === 'Attribute' && par.value === n;
      info.set(g.inst, { arr: text(n.value), idx: text(n.index), direct });
      if (!direct) edits.push({ start: n.start, end: n.end, text: text(n.index) });
    }
    for (const a of c.accesses) {
      const m = nodeOf(a.inst);
      const member: PyNode = m.type === 'Attribute' ? m : m.target;
      const inf = info.get(a.element)!;
      const ok = proven.get(a.element) || p.options.bounds === 'assume';
      let idx = inf.direct ? inf.idx : text(member.value);
      if (!ok) idx = `_vsc_ix(${inf.arr}, ${idx})`;
      const e = { start: member.start, end: member.end, text: `${inf.arr}.${col(a.field, c.fields.indexOf(a.field))}[${idx}]` };
      fieldEdits.set(`${e.start}:${e.end}`, e);
    }
  }
  if (classes.length === 0) return source;
  edits.push(...fieldEdits.values());
  edits.sort((x, y) => y.start - x.start);
  let out = source;
  let last = Infinity;
  for (const e of edits) {
    if (e.end > last) throw new Error(`internal error: overlapping rewrites at ${e.start}`);
    out = out.slice(0, e.start) + e.text + out.slice(e.end);
    last = e.start;
  }
  // Prelude after a module docstring and `from __future__` imports.
  const head = /^((?:#[^\n]*\n)*(?:\s*("""[\s\S]*?"""|'''[\s\S]*?''')\s*\n)?(?:from __future__ import [^\n]*\n)*)/.exec(out)![0];
  return head + HELPERS + classes.join('\n') + '\n\n' + out.slice(head.length);
}

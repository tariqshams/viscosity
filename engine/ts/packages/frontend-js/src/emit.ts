// Emitting JavaScript from a layout plan (book chapters 94, 103–107).
//
// Viscosity rewrites only what it must: every edit is a replacement of one
// source range, and everything else is copied through byte for byte. That
// keeps comments, formatting and unrelated code exactly as the programmer
// wrote it.
//
// For a collection planned as SoA:
//   const ps = [];                 ->  const ps = new __Vsc_ps();
//   ps.push({ x: a, y: b });       ->  ps.push(a, b);
//   ps[i].x                        ->  ps.x[i]
//   const p = ps[i]; p.x           ->  const p = i; ps.x[p]     (p holds an index)
//   for (const p of ps) p.x        ->  for (let p = 0; p < ps.length; p++) ps.x[p]
// Accesses not proven in bounds get a check that throws the same TypeError
// the original code would have thrown.
import type { CollectionPlan, Plan } from '../../core/src/plan.ts';
import type { Inst } from '../../core/src/vir.ts';
import type { Node } from './estree.ts';
import type { Resolution } from './resolve.ts';

interface Edit { start: number; end: number; text: string }

const RESERVED = new Set(['length', 'push', 'grow', 'of', 'constructor', 'prototype', 'get', 'cap', 'data']);
export const columnName = (field: string, i: number) =>
  /^[A-Za-z_$][\w$]*$/.test(field) && !RESERVED.has(field) ? field : `f${i}_`;

/** Column names for a record's fields, renamed where needed and never clashing. */
export function columnNames(fields: string[]): string[] {
  const used = new Set<string>();
  const kept = new Set(fields.filter((f, i) => columnName(f, i) === f));
  return fields.map((f, i) => {
    let n = columnName(f, i);
    if (n !== f) while (kept.has(n) || used.has(n)) n += '_';
    used.add(n);
    return n;
  });
}

export function containerClass(cp: CollectionPlan, cls = `__Vsc_${cp.collection.name}`): string {
  const c = cp.collection;
  const F = c.fields.length;
  const cols = columnNames(c.fields);
  const params = c.fields.map((_, i) => `v${i}`).join(', ');
  if (cp.layout === 'aosoa') {
    if (c.numericFields.size !== c.fields.length) throw new Error(`AoSoA needs every field of "${c.name}" to be numeric`);
    const B = cp.blockSize;
    const shift = Math.log2(B);
    if (!Number.isInteger(shift)) throw new Error('AoSoA block size must be a power of two');
    return [
      `// Generated by Viscosity: "${c.name}" stored as AoSoA, blocks of ${B} (fields ${c.fields.join(', ')}).`,
      `class ${cls} {`,
      `  constructor(cap = ${B * 2}) { this.length = 0; this.cap = Math.ceil(cap / ${B}) * ${B}; this.data = new Float64Array(this.cap * ${F}); }`,
      `  static of(...v) { const c = new ${cls}(v.length / ${F}); for (let i = 0; i < v.length; i += ${F}) c.push(${c.fields.map((_, k) => `v[i + ${k}]`).join(', ')}); return c; }`,
      `  push(${params}) { const n = this.length; if (n === this.cap) this.grow(); const b = (n >> ${shift}) * ${F * B} + (n & ${B - 1}); ${c.fields.map((_, k) => `this.data[b + ${k * B}] = v${k};`).join(' ')} return (this.length = n + 1); }`,
      `  grow() { const d = new Float64Array(this.cap * 2 * ${F}); d.set(this.data); this.data = d; this.cap *= 2; }`,
      `}`,
    ].join('\n');
  }
  // Typed columns for numeric fields, plain arrays for the rest.
  const typed = cols.filter((_, k) => c.numericFields.has(c.fields[k]));
  const plain = cols.filter((_, k) => !c.numericFields.has(c.fields[k]));
  return [
    `// Generated by Viscosity: "${c.name}" stored as a struct of arrays (fields ${c.fields.join(', ')}).`,
    `class ${cls} {`,
    `  constructor(cap = 16) { this.length = 0; this.cap = cap; ${typed.map((n) => `this.${n} = new Float64Array(cap);`).join(' ')}${plain.map((n) => ` this.${n} = [];`).join('')} }`,
    `  static of(...v) { const c = new ${cls}(Math.max(16, v.length / ${F})); for (let i = 0; i < v.length; i += ${F}) c.push(${c.fields.map((_, k) => `v[i + ${k}]`).join(', ')}); return c; }`,
    `  push(${params}) { const n = this.length; if (n === this.cap) this.grow(); ${cols.map((n, k) => `this.${n}[n] = v${k};`).join(' ')} return (this.length = n + 1); }`,
    `  grow() { const cap = (this.cap *= 2); let t; ${typed.map((n) => `t = new Float64Array(cap); t.set(this.${n}); this.${n} = t;`).join(' ')} }`,
    `}`,
  ].join('\n');
}

const BOUNDS_HELPER = [
  '// Generated by Viscosity: bounds check matching the original TypeError.',
  'function __vsc_bc(c, i, f, w) {',
  '  if (i >>> 0 === i && i < c.length) return i;',
  '  throw new TypeError(w ? `Cannot set properties of undefined (setting \'${f}\')` : `Cannot read properties of undefined (reading \'${f}\')`);',
  '}',
].join('\n');

export function emitJs(source: string, program: Node, res: Resolution, p: Plan): string {
  const edits: Edit[] = [];
  const prelude: string[] = [];
  let needBounds = false;
  let needAosoa = false;
  // Field edits keyed by range: a compound assignment (p.x += 1) reads and
  // writes the same member, so it would otherwise be edited twice. Keep the
  // read: JavaScript reads p.x first, so out of bounds it throws "Cannot
  // read properties of undefined", not "Cannot set".
  const fieldEdits = new Map<string, Edit & { write: boolean }>();
  const fieldEdit = (e: Edit, write: boolean) => {
    const k = `${e.start}:${e.end}`;
    const prev = fieldEdits.get(k);
    if (!prev || (!write && prev.write)) fieldEdits.set(k, { ...e, write });
  };
  const text = (n: Node) => source.slice(n.start, n.end);
  const nodeOf = (i: Inst) => i.src!.node as Node;

  const classNames = new Set<string>();
  for (const cp of p.collections) {
    if (cp.layout === 'aos') continue;
    const c = cp.collection;
    // Two collections can share a name (in different functions): number them.
    let cls = `__Vsc_${c.name}`;
    for (let k = 2; classNames.has(cls); k++) cls = `__Vsc_${c.name}_${k}`;
    classNames.add(cls);
    const cols = columnNames(c.fields);
    const col = (f: string) => cols[c.fields.indexOf(f)];
    prelude.push(containerClass(cp, cls));
    const F = c.fields.length;
    const B = cp.blockSize;
    const slot = (arr: string, f: string, idx: string, simpleIdx: boolean): string => {
      if (cp.layout === 'soa') return `${arr}.${col(f)}[${idx}]`;
      const k = c.fields.indexOf(f);
      const sh = Math.log2(B);
      const at = simpleIdx
        ? `((${idx}) >> ${sh}) * ${F * B} + ${k * B} + ((${idx}) & ${B - 1})`
        : `__vsc_aosoa(${idx}, ${sh}, ${F * B}, ${k * B}, ${B - 1})`;
      if (!simpleIdx) needAosoa = true;
      return `${arr}.data[${at}]`;
    };

    // 1. Creation.
    const init = nodeOf(c.init);
    if (c.init.op === 'array.empty') {
      edits.push({ start: init.start, end: init.end, text: `new ${cls}()` });
    } else {
      const vals = c.initRecords.map((r) => (nodeOf(r).properties as Node[]).map((pr) => text(pr.value)).join(', '));
      edits.push({ start: init.start, end: init.end, text: `${cls}.of(${vals.join(', ')})` });
    }

    // 2. push({...}) -> push(a, b, ...)
    for (const pu of c.pushes) {
      const call = nodeOf(pu);
      const obj = call.arguments[0];
      edits.push({ start: obj.start, end: obj.end, text: (obj.properties as Node[]).map((pr) => text(pr.value)).join(', ') });
    }

    // 3. Elements. Decide, for each index.get, whether it is used directly
    //    (arr[i].x) or through a variable (const p = arr[i]).
    const proven = new Map(c.indexGets.map((g) => [g.inst, g.boundsProven]));
    const elementInfo = new Map<Inst, { arr: string; idx: string; simple: boolean; direct: boolean; forOf: Node | null }>();
    for (const g of c.indexGets) {
      const n = nodeOf(g.inst);
      if (n.type === 'ForOfStatement') {
        const decl = n.left.type === 'VariableDeclaration' ? n.left.declarations[0].id : n.left;
        elementInfo.set(g.inst, { arr: text(n.right), idx: decl.name, simple: true, direct: false, forOf: n });
        continue;
      }
      const parent = res.parent.get(n);
      const direct = !!parent && parent.type === 'MemberExpression' && parent.object === n;
      const idxNode = n.property;
      elementInfo.set(g.inst, {
        arr: text(n.object), idx: text(idxNode), simple: idxNode.type === 'Identifier' || idxNode.type === 'Literal',
        direct, forOf: null,
      });
      if (!direct) {
        // The variable now holds the index, not an object.
        edits.push({ start: n.start, end: n.end, text: text(idxNode) });
      }
    }
    for (const [g, info] of elementInfo) {
      if (info.forOf) {
        const n = info.forOf;
        edits.push({ start: n.left.start, end: n.right.end, text: `let ${info.idx} = 0; ${info.idx} < ${info.arr}.length; ${info.idx}++` });
      }
      void g;
    }

    // 4. Field reads and writes.
    for (const a of c.accesses) {
      const m = nodeOf(a.inst);
      // For writes, the source node is the assignment/update; find the member.
      const member = m.type === 'MemberExpression' ? m : m.type === 'AssignmentExpression' ? m.left : m.argument;
      const info = elementInfo.get(a.element)!;
      const ok = proven.get(a.element) || p.options.bounds === 'assume';
      if (info.direct) {
        let idx = info.idx;
        if (!ok) { idx = `__vsc_bc(${info.arr}, ${idx}, '${a.field}', ${a.kind === 'write'})`; needBounds = true; }
        fieldEdit({ start: member.start, end: member.end, text: slot(info.arr, a.field, idx, info.simple && ok) }, a.kind === 'write');
      } else {
        let idx = text(member.object);
        if (!ok) { idx = `__vsc_bc(${info.arr}, ${idx}, '${a.field}', ${a.kind === 'write'})`; needBounds = true; }
        fieldEdit({ start: member.start, end: member.end, text: slot(info.arr, a.field, idx, ok) }, a.kind === 'write');
      }
    }
  }
  if (prelude.length === 0) return source;
  for (const e of fieldEdits.values()) edits.push(e);
  if (needBounds) prelude.push(BOUNDS_HELPER);
  if (needAosoa) prelude.push('function __vsc_aosoa(i, sh, stride, off, mask) { return (i >> sh) * stride + off + (i & mask); }');

  // Apply edits back to front; overlapping edits would mean a bug.
  edits.sort((x, y) => y.start - x.start);
  let out = source;
  let lastStart = Infinity;
  for (const e of edits) {
    if (e.end > lastStart) throw new Error(`internal error: overlapping rewrites at ${e.start}-${e.end}`);
    out = out.slice(0, e.start) + e.text + out.slice(e.end);
    lastStart = e.start;
  }
  // The prelude goes after any leading directives ("use strict") and shebang.
  const head = /^(#![^\n]*\n)?(\s*(['"])use strict\3;?\s*\n)?/.exec(out)![0];
  return head + prelude.join('\n') + '\n' + out.slice(head.length);
}


// Builds @viscosity/wasm: the Rust engine (crates/wasm) compiled to
// WebAssembly, with wasm-bindgen glue for Node (dist/node) and for browsers
// and bundlers (dist/web).
//
//   node build.mjs              cargo build + wasm-bindgen + wasm-opt
//   node build.mjs --no-opt     skip wasm-opt
//   node build.mjs --no-cargo   reuse the last cargo build
//   node build.mjs --book       also copy the web build into the book
//
// Needs the wasm32-unknown-unknown target and wasm-bindgen-cli at exactly
// the version in Cargo.lock (`cargo install wasm-bindgen-cli --version X`).
// wasm-opt is optional: $WASM_OPT, then node_modules/.bin (the binaryen
// devDependency), then the PATH.
import { execFileSync } from 'node:child_process';
import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { gzipSync } from 'node:zlib';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const ws = join(here, '..', '..'); // engine/rust
const repo = join(ws, '..', '..');
const args = new Set(process.argv.slice(2));
const sh = (cmd, a, opts = {}) => execFileSync(cmd, a, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit'], ...opts });
const log = (s) => console.log(`[wasm] ${s}`);

// 1. cargo
const target = process.env.CARGO_TARGET_DIR ?? join(ws, 'target');
if (!args.has('--no-cargo')) {
  log('cargo build --release --target wasm32-unknown-unknown -p viscosity-wasm');
  execFileSync('cargo', ['build', '--release', '--target', 'wasm32-unknown-unknown', '-p', 'viscosity-wasm'], { cwd: ws, stdio: 'inherit' });
}
const raw = join(target, 'wasm32-unknown-unknown', 'release', 'viscosity_wasm.wasm');
if (!existsSync(raw)) throw new Error(`${raw} not found; run without --no-cargo`);

// 2. wasm-bindgen, at the version the crate links against.
const lock = readFileSync(join(ws, 'Cargo.lock'), 'utf8');
const want = lock.match(/name = "wasm-bindgen"\nversion = "([^"]+)"/)?.[1];
let have = '';
try { have = sh('wasm-bindgen', ['--version']).trim().split(' ').pop(); } catch { /* missing */ }
if (have !== want) throw new Error(`wasm-bindgen-cli ${want} is required (found ${have || 'none'}): cargo install wasm-bindgen-cli --version ${want}`);

const dist = join(here, 'dist');
rmSync(dist, { recursive: true, force: true });
for (const t of ['nodejs', 'web']) {
  const out = join(dist, t === 'nodejs' ? 'node' : 'web');
  log(`wasm-bindgen ${have} --target ${t}`);
  sh('wasm-bindgen', ['--target', t, '--out-dir', out, raw]);
}

// 3. wasm-opt (optional).
const findOpt = () => {
  const cands = [process.env.WASM_OPT, join(here, 'node_modules', '.bin', 'wasm-opt'), 'wasm-opt'].filter(Boolean);
  for (const c of cands) { try { sh(c, ['--version']); return c; } catch { /* next */ } }
  return null;
};
const opt = args.has('--no-opt') ? null : findOpt();
// The features rustc enables by default for wasm32-unknown-unknown.
const features = ['--enable-bulk-memory', '--enable-nontrapping-float-to-int', '--enable-sign-ext', '--enable-mutable-globals', '--enable-reference-types', '--enable-multivalue'];
const sizes = { cargo: statSync(raw).size };
for (const d of ['node', 'web']) {
  const f = join(dist, d, 'viscosity_wasm_bg.wasm');
  sizes[`${d}Bindgen`] = statSync(f).size;
  if (opt) {
    log(`${opt.endsWith('wasm-opt') ? 'wasm-opt' : opt} -O3 ${d}`);
    sh(opt, ['-O3', ...features, f, '-o', f]);
  }
  sizes[d] = statSync(f).size;
  sizes[`${d}Gzip`] = gzipSync(readFileSync(f), { level: 9 }).length;
}
if (!opt) log(args.has('--no-opt') ? 'wasm-opt skipped (--no-opt)' : 'wasm-opt not found; the .wasm is not post-optimized');

// wasm-bindgen writes its own package.json and .gitignore; ours is the one above.
for (const d of ['node', 'web']) for (const f of ['package.json', '.gitignore']) rmSync(join(dist, d, f), { force: true });
// The nodejs target is CommonJS; mark that directory so "type": "module" doesn't apply.
writeFileSync(join(dist, 'node', 'package.json'), '{ "type": "commonjs" }\n');

// 4. Licences: Viscosity's, and the full texts of every Rust crate linked
// into the .wasm (normal dependencies for wasm32, without proc macros).
copyFileSync(join(repo, 'LICENSE'), join(here, 'LICENSE'));
writeFileSync(join(here, 'THIRD_PARTY_LICENSES.txt'), thirdParty());
log('wrote LICENSE and THIRD_PARTY_LICENSES.txt');

// 5. --book: the book's Playground loads the web build on demand. The glue
// goes next to the TS engine bundle (book/src/vendor), the module into
// book/public/wasm (served as /wasm/viscosity_wasm_bg.wasm, never bundled).
if (args.has('--book')) {
  const book = join(repo, 'book');
  const banner = `// Viscosity Rust engine, wasm-bindgen ${have} glue (web target). (c) Tariq Shams, MIT.\n// Generated by engine/rust/packages/wasm/build.mjs --book; the module is book/public/wasm/viscosity_wasm_bg.wasm.\n`;
  // init() with no argument would resolve the module next to the glue, and
  // Vite would try to bundle it; point the default at the public copy.
  const glue = readFileSync(join(dist, 'web', 'viscosity_wasm.js'), 'utf8');
  const def = "new URL('viscosity_wasm_bg.wasm', import.meta.url)";
  if (!glue.includes(def)) throw new Error('wasm-bindgen glue changed: default module URL not found');
  writeFileSync(join(book, 'src', 'vendor', 'viscosity_wasm.js'), banner + glue.replace(def, "'/wasm/viscosity_wasm_bg.wasm'"));
  copyFileSync(join(dist, 'web', 'viscosity_wasm.d.ts'), join(book, 'src', 'vendor', 'viscosity_wasm.d.ts'));
  mkdirSync(join(book, 'public', 'wasm'), { recursive: true });
  copyFileSync(join(dist, 'web', 'viscosity_wasm_bg.wasm'), join(book, 'public', 'wasm', 'viscosity_wasm_bg.wasm'));
  copyFileSync(join(here, 'THIRD_PARTY_LICENSES.txt'), join(book, 'public', 'wasm', 'THIRD_PARTY_LICENSES.txt'));
  log('copied the web build into book/src/vendor and book/public/wasm');
}

const kb = (n) => `${(n / 1024).toFixed(0)} KiB`;
log(`sizes: cargo ${kb(sizes.cargo)}, after wasm-bindgen ${kb(sizes.webBindgen)}, final web ${kb(sizes.web)} (${kb(sizes.webGzip)} gzipped), node ${kb(sizes.node)}`);
writeFileSync(join(dist, 'sizes.json'), JSON.stringify({ wasmBindgen: have, wasmOpt: opt ? sh(opt, ['--version']).trim() : null, bytes: sizes }, null, 2) + '\n');

function thirdParty() {
  const tree = sh('cargo', ['tree', '-p', 'viscosity-wasm', '--target', 'wasm32-unknown-unknown', '-e', 'normal,no-proc-macro', '--prefix', 'none', '-f', '{p}|{l}'], { cwd: ws });
  const crates = new Map();
  for (const line of tree.split('\n')) {
    const m = line.replace(' (*)', '').match(/^(\S+) v(\S+)( \((.+)\))?\|(.*)$/);
    if (!m || m[4]?.startsWith('/')) continue; // skip blank lines and our own path crates
    crates.set(`${m[1]} ${m[2]}`, { name: m[1], version: m[2], license: m[5] });
  }
  const meta = JSON.parse(sh('cargo', ['metadata', '--format-version', '1', '--filter-platform', 'wasm32-unknown-unknown'], { cwd: ws, maxBuffer: 64 << 20 }));
  const dirOf = new Map(meta.packages.map((p) => [`${p.name} ${p.version}`, dirname(p.manifest_path)]));
  // oxc's crates are published without their licence file; ours are copies
  // of the repositories' files (github.com/oxc-project/oxc/blob/main/LICENSE
  // and github.com/oxc-project/oxc-index-vec/blob/main/LICENSE-MIT).
  const fallback = (name) => name === 'oxc_index' ? ['licenses/oxc-index-vec-LICENSE-MIT'] : name.startsWith('oxc') ? ['licenses/oxc-LICENSE'] : [];
  const sorted = [...crates.values()].sort((a, b) => a.name.localeCompare(b.name));
  const texts = new Map(); // hash -> { text, users: [] }
  for (const c of sorted) {
    const dir = dirOf.get(`${c.name} ${c.version}`);
    let files = readdirSync(dir).filter((f) => /^(licen[cs]e|copying|unlicense|notice)/i.test(f) && statSync(join(dir, f)).isFile()).map((f) => join(dir, f));
    if (!files.length) files = fallback(c.name).map((f) => join(here, f));
    if (!files.length) throw new Error(`${c.name} ${c.version}: no licence file found in ${dir}`);
    for (const f of files) {
      const text = readFileSync(f, 'utf8').replace(/\r\n/g, '\n').trim();
      const h = createHash('sha256').update(text).digest('hex');
      if (!texts.has(h)) texts.set(h, { text, users: [] });
      texts.get(h).users.push(`${c.name} ${c.version} (${c.license}; ${f.split('/').pop()})`);
    }
  }
  const rule = '='.repeat(78);
  let out = `Third-party software in @viscosity/wasm\n\nviscosity_wasm_bg.wasm is the Viscosity Rust engine (MIT, see LICENSE)\nstatically linked with the ${crates.size} Rust crates below. Each crate's licence\nfiles are reproduced in full; crates that ship an identical text share one\ncopy. Where a crate is offered under a choice of licences ("A OR B"), it is\nused here under the MIT licence where MIT is one of the choices, and all of\nits licence files are still included.\n\nCrates:\n${sorted.map((c) => `  ${c.name} ${c.version}  ${c.license}`).join('\n')}\n`;
  for (const { text, users } of texts.values()) out += `\n${rule}\n${users.join('\n')}\n${rule}\n\n${text}\n`;
  return out;
}

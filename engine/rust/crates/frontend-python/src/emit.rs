//! Emitting Python with column storage (book chapter 116). Like the JS
//! emitter, it only replaces the source ranges it must.
//!
//! ```text
//!   ps = []                         ->  ps = _Vsc_ps()
//!   ps.append(P(a, b))              ->  ps.append(a, b)
//!   ps[i].x                         ->  ps.x[i]
//!   p = ps[i]; p.x                  ->  p = i; ps.x[p]
//!   for p in ps:                    ->  for p in _vsc_iter(ps):
//! ```
//!
//! Columns are `array('d')` for fields proven to always hold floats, and
//! plain lists otherwise. In Python an int stored in `array('d')` would come
//! back as a float and print as "1.0", so ints never go into typed columns.
//!
//! Port of `emit.ts`.

use std::collections::{HashMap, HashSet};

use indexmap::IndexMap;
use viscosity_core::{Bounds, CollectionPlan, CompileError, Layout, Plan};
use viscosity_vir::{Module, Op, ValueId};

use crate::lower::PyLowered;
use crate::parser::{Kind, NodeId};

struct Edit {
    start: u32,
    end: u32,
    text: String,
}

const RESERVED: &[&str] = &["n", "append", "_of", "__len__", "__init__", "__slots__"];

fn col(f: &str, i: usize) -> String {
    if RESERVED.contains(&f) || f.starts_with("__") {
        format!("f{i}_")
    } else {
        f.to_string()
    }
}

/// Column names for a record's fields, renamed where needed and never
/// clashing.
pub fn column_names(fields: &[String]) -> Vec<String> {
    let mut used = HashSet::new();
    let kept: HashSet<&str> =
        fields.iter().enumerate().filter(|(i, f)| col(f, *i) == **f).map(|(_, f)| f.as_str()).collect();
    fields
        .iter()
        .enumerate()
        .map(|(i, f)| {
            let mut n = col(f, i);
            if n != *f {
                while kept.contains(n.as_str()) || used.contains(&n) {
                    n.push('_');
                }
            }
            used.insert(n.clone());
            n
        })
        .collect()
}

fn container_class(cp: &CollectionPlan, cls: &str) -> String {
    let c = &cp.collection;
    let cols = column_names(&c.fields);
    let mut lines = vec![
        format!(
            "# Generated by Viscosity: \"{}\" stored as a struct of arrays (fields {}).",
            c.name,
            c.fields.join(", ")
        ),
        format!("class {cls}:"),
        format!("    __slots__ = ('n', {})", cols.iter().map(|n| format!("'{n}'")).collect::<Vec<_>>().join(", ")),
        "    def __init__(self):".into(),
        "        self.n = 0".into(),
    ];
    for (k, n) in cols.iter().enumerate() {
        let init = if c.numeric_fields.contains(&c.fields[k]) { "_vsc_array('d')" } else { "[]" };
        lines.push(format!("        self.{n} = {init}"));
    }
    let params: Vec<String> = (0..cols.len()).map(|k| format!("v{k}")).collect();
    lines.push(format!("    def append(self, {}):", params.join(", ")));
    for (k, n) in cols.iter().enumerate() {
        lines.push(format!("        self.{n}.append(v{k})"));
    }
    lines.extend([
        "        self.n += 1".into(),
        "    def __len__(self):".into(),
        "        return self.n".into(),
        "    @classmethod".into(),
        "    def _of(cls, *v):".into(),
        "        c = cls()".into(),
        format!("        for i in range(0, len(v), {}):", c.fields.len()),
        format!(
            "            c.append({})",
            (0..c.fields.len()).map(|k| format!("v[i + {k}]")).collect::<Vec<_>>().join(", ")
        ),
        "        return c".into(),
    ]);
    lines.join("\n")
}

const HELPERS: &str = "from array import array as _vsc_array
# Generated by Viscosity: bounds check matching list's IndexError.
def _vsc_ix(c, i):
    if -c.n <= i < c.n:
        return i
    raise IndexError('list index out of range')
# Generated by Viscosity: like iterating a list, re-checks the length each step.
def _vsc_iter(c):
    i = 0
    while i < c.n:
        yield i
        i += 1
";

/// JavaScript's `\s`.
fn is_js_space(c: char) -> bool {
    matches!(
        c,
        '\t' | '\n' | '\u{b}' | '\u{c}' | '\r' | ' ' | '\u{a0}' | '\u{1680}' | '\u{2000}'
            ..='\u{200a}' | '\u{2028}' | '\u{2029}' | '\u{202f}' | '\u{205f}' | '\u{3000}' | '\u{feff}'
    )
}

/// The length of the match of
/// `/^((?:#[^\n]*\n)*(?:\s*("""[\s\S]*?"""|'''[\s\S]*?''')\s*\n)?(?:from __future__ import [^\n]*\n)*)/`:
/// comment lines, a module docstring and `from __future__` imports, which
/// the prelude goes after.
fn prelude_len(s: &str) -> usize {
    let line_end = |from: usize| s[from..].find('\n').map(|k| from + k + 1);
    let mut i = 0;
    while s[i..].starts_with('#') {
        match line_end(i) {
            Some(e) => i = e,
            None => break,
        }
    }
    // The optional docstring: `\s*` is greedy, `[\s\S]*?` lazy, and the
    // closing `\s*\n` ends after the last line break of the spaces that
    // follow the closing quotes.
    let mut j = i;
    while let Some(c) = s[j..].chars().next().filter(|&c| is_js_space(c)) {
        j += c.len_utf8();
    }
    for q in ["\"\"\"", "'''"] {
        if !s[j..].starts_with(q) {
            continue;
        }
        let mut k = j + 3;
        while let Some(at) = s[k..].find(q) {
            let close = k + at + 3;
            let mut end = None;
            let mut w = close;
            while let Some(c) = s[w..].chars().next().filter(|&c| is_js_space(c)) {
                w += c.len_utf8();
                if c == '\n' {
                    end = Some(w);
                }
            }
            if let Some(e) = end {
                i = e;
                break;
            }
            k += at + 1;
        }
    }
    while s[i..].starts_with("from __future__ import ") {
        match line_end(i) {
            Some(e) => i = e,
            None => break,
        }
    }
    i
}

struct Info {
    arr: String,
    idx: String,
    direct: bool,
}

pub fn emit_python(source: &str, m: &Module, low: &PyLowered, p: &Plan) -> Result<String, CompileError> {
    let ast = &low.ast;
    let len = source.len() as u32;
    let slice = |start: u32, end: u32| -> &str {
        let (a, b) = (start.min(len) as usize, end.min(len) as usize);
        &source[a..b.max(a)]
    };
    let text = |n: NodeId| -> &str {
        let node = ast.node(n);
        slice(node.start, node.end)
    };
    let node_of = |v: ValueId| -> NodeId { m.inst(v).src.expect("a source position").node.0 };
    let mut edits: Vec<Edit> = Vec::new();
    let mut classes: Vec<String> = Vec::new();
    let mut field_edits: IndexMap<(u32, u32), Edit> = IndexMap::new();
    let mut class_names: HashSet<String> = HashSet::new();

    for cp in &p.collections {
        match cp.layout {
            Layout::Aos => continue,
            Layout::Aosoa => return Err(CompileError("AoSoA is not supported for Python".into())),
            Layout::Soa => {}
        }
        let c = &cp.collection;
        let mut cls = format!("_Vsc_{}", c.name);
        let mut k = 2;
        while class_names.contains(&cls) {
            cls = format!("_Vsc_{}_{k}", c.name);
            k += 1;
        }
        class_names.insert(cls.clone());
        classes.push(container_class(cp, &cls));
        let record_args = |r: ValueId| -> String {
            let call = node_of(r);
            let dc = &low.dataclasses[low.record_class[&r]];
            let Kind::Call { args, keywords, .. } = ast.kind(call) else { unreachable!("a dataclass call") };
            let mut vals: Vec<&str> = args.iter().map(|&a| text(a)).collect();
            let rest = dc.fields.get(args.len()..).unwrap_or(&[]);
            let mut k = 0;
            for f in rest {
                if k < keywords.len() && keywords[k].0 == *f {
                    vals.push(text(keywords[k].1));
                    k += 1;
                } else {
                    vals.push(text(dc.default_of(f).expect("a default")));
                }
            }
            vals.join(", ")
        };

        let init = ast.node(node_of(c.init));
        let init_text = if matches!(m.inst(c.init).op, Op::ArrayEmpty) {
            format!("{cls}()")
        } else {
            format!("{cls}._of({})", c.init_records.iter().map(|&r| record_args(r)).collect::<Vec<_>>().join(", "))
        };
        edits.push(Edit { start: init.start, end: init.end, text: init_text });
        for &pu in &c.pushes {
            let r = m.inst(pu).args[1];
            let rn = ast.node(node_of(r));
            edits.push(Edit { start: rn.start, end: rn.end, text: record_args(r) });
        }

        let mut info: HashMap<ValueId, Info> = HashMap::new();
        let proven: HashMap<ValueId, bool> = c.index_gets.iter().map(|g| (g.inst, g.bounds_proven)).collect();
        for g in &c.index_gets {
            let n = node_of(g.inst);
            match ast.kind(n) {
                Kind::For { target, iter, .. } => {
                    let it = ast.node(*iter);
                    edits.push(Edit { start: it.start, end: it.end, text: format!("_vsc_iter({})", text(*iter)) });
                    let idx = ast.name_of(*target).expect("a name").to_string();
                    info.insert(g.inst, Info { arr: text(*iter).to_string(), idx, direct: false });
                }
                Kind::Subscript { value, index } => {
                    let direct = low.parent[n as usize]
                        .is_some_and(|par| matches!(ast.kind(par), Kind::Attribute { value: v, .. } if *v == n));
                    info.insert(g.inst, Info { arr: text(*value).to_string(), idx: text(*index).to_string(), direct });
                    if !direct {
                        let node = ast.node(n);
                        edits.push(Edit { start: node.start, end: node.end, text: text(*index).to_string() });
                    }
                }
                _ => unreachable!("an element read is a subscript or a for loop"),
            }
        }
        let names = column_names(&c.fields);
        for a in &c.accesses {
            let mn = node_of(a.inst);
            let member = match ast.kind(mn) {
                Kind::Attribute { .. } => Some(mn),
                Kind::Assign { target, .. } | Kind::AugAssign { target, .. } | Kind::AnnAssign { target, .. } => {
                    Some(*target)
                }
                _ => None,
            };
            let inf = &info[&a.element];
            let ok = proven.get(&a.element).copied().unwrap_or(false) || p.options.bounds == Bounds::Assume;
            let mut idx = if inf.direct {
                inf.idx.clone()
            } else {
                // `len(e)` on an element whose record has a `length` field:
                // the reference fails here the same way.
                let Some(Kind::Attribute { value, .. }) = member.map(|x| ast.kind(x)) else {
                    return Err(CompileError("Cannot read properties of undefined (reading 'value')".into()));
                };
                text(*value).to_string()
            };
            if !ok {
                idx = format!("_vsc_ix({}, {idx})", inf.arr);
            }
            let Some(member) = member else {
                return Err(CompileError("Cannot read properties of undefined (reading 'start')".into()));
            };
            let mnode = ast.node(member);
            let k = c.fields.iter().position(|f| *f == a.field).expect("a field of the record");
            let e = Edit { start: mnode.start, end: mnode.end, text: format!("{}.{}[{idx}]", inf.arr, names[k]) };
            field_edits.insert((e.start, e.end), e);
        }
    }
    if classes.is_empty() {
        return Ok(source.to_string());
    }
    edits.extend(field_edits.into_values());
    // Stable, like Array.prototype.sort: equal starts keep their order.
    edits.sort_by_key(|e| std::cmp::Reverse(e.start));
    let mut out = source.to_string();
    let mut last = u32::MAX;
    for e in &edits {
        if e.end > last {
            return Err(CompileError(format!("internal error: overlapping rewrites at {}", e.start)));
        }
        let olen = out.len() as u32;
        let (a, b) = (e.start.min(olen) as usize, e.end.min(olen) as usize);
        out.replace_range(a..b.max(a), &e.text);
        last = e.start;
    }
    let head = prelude_len(&out);
    Ok(format!("{}{HELPERS}{}\n\n{}", &out[..head], classes.join("\n"), &out[head..]))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn column_names_avoid_reserved_names_and_clashes() {
        let f = |v: &[&str]| column_names(&v.iter().map(|s| s.to_string()).collect::<Vec<_>>());
        assert_eq!(f(&["x", "n", "append"]), vec!["x", "f1_", "f2_"]);
        assert_eq!(f(&["n", "f0_"]), vec!["f0__", "f0_"]);
        assert_eq!(f(&["__a", "_of"]), vec!["f0_", "f1_"]);
    }

    #[test]
    fn the_prelude_goes_after_comments_docstring_and_future_imports() {
        let src = "# a\n\"\"\"doc\"\"\" \nfrom __future__ import annotations\nx = 1\n";
        assert_eq!(&src[prelude_len(src)..], "x = 1\n");
        // The docstring's closing quotes must be followed by a line break.
        let src = "\"\"\"a\"\"\" x\n\"\"\"\n\ny\n";
        assert_eq!(&src[prelude_len(src)..], "y\n");
        assert_eq!(prelude_len("x = 1\n"), 0);
        assert_eq!(prelude_len("# no newline"), 0);
    }
}

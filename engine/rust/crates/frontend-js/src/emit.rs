//! Emitting JavaScript from a layout plan (the book's chapters “Emitting JavaScript” and “Generating SoA storage” to “AoSoA code generation”).
//!
//! Viscosity rewrites only what it must: every edit replaces one source
//! range, and everything else is copied through byte for byte. That keeps
//! comments, formatting and unrelated code exactly as the programmer wrote
//! them.
//!
//! For a collection planned as SoA:
//!
//! ```text
//! const ps = [];                 ->  const ps = new __Vsc_ps();
//! ps.push({ x: a, y: b });       ->  ps.push(a, b);
//! ps[i].x                        ->  ps.x[i]
//! const p = ps[i]; p.x           ->  const p = i; ps.x[p]     (p holds an index)
//! for (const p of ps) p.x        ->  for (let p = 0; p < ps.length; p++) ps.x[p]
//! ```
//!
//! Accesses not proven in bounds get a check that throws the same
//! `TypeError` the original code would have thrown.
//!
//! Offsets are UTF-8 byte offsets into the source (oxc's spans), so slicing
//! and splicing the Rust string gives exactly the text the TS reference gets
//! by slicing its UTF-16 string at the corresponding offsets.

use indexmap::IndexMap;
use oxc_span::Span;
use rustc_hash::FxHashSet as HashSet;
use viscosity_core::{AccessKind, Bounds, CollectionPlan, CompileError, Layout, Plan, RhsEffect};
use viscosity_vir::{js_number, Module, Op, ValueId};

use crate::lower::{JsNode, Value};

/// One replacement of the source range `start..end` (an insertion when
/// they are equal).
#[derive(Clone, Debug)]
struct Edit {
    start: u32,
    end: u32,
    text: String,
    /// Orders insertions at one position: the one closing the outer
    /// assignment (the smaller rank) is applied first, so it ends up last.
    rank: u32,
}

impl Edit {
    fn new(start: u32, end: u32, text: String) -> Self {
        Edit { start, end, text, rank: 0 }
    }
}

/// Field names that would clash with the container class's own members.
const RESERVED: &[&str] = &["length", "push", "grow", "of", "constructor", "prototype", "get", "cap", "data"];

/// The column name of field `i`: the field name if it is a plain, safe
/// identifier, else `f{i}_`.
pub fn column_name(field: &str, i: usize) -> String {
    let mut chars = field.chars();
    let ident = chars.next().is_some_and(|c| c.is_ascii_alphabetic() || c == '_' || c == '$')
        && chars.all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '$');
    if ident && !RESERVED.contains(&field) {
        field.to_string()
    } else {
        format!("f{i}_")
    }
}

/// Column names for a record's fields, renamed where needed (see
/// [`column_name`]) and never clashing: a renamed column gets `_` appended
/// until it differs from every kept field name and every earlier column.
pub fn column_names(fields: &[String]) -> Vec<String> {
    let kept: HashSet<&str> =
        fields.iter().enumerate().filter(|(i, f)| column_name(f, *i) == **f).map(|(_, f)| f.as_str()).collect();
    let mut used: HashSet<String> = HashSet::default();
    fields
        .iter()
        .enumerate()
        .map(|(i, f)| {
            let mut n = column_name(f, i);
            if n != *f {
                while kept.contains(n.as_str()) || used.contains(&n) {
                    n.push('_');
                }
            }
            used.insert(n.clone());
            n
        })
        .collect()
}

/// `log2(b)` if `b` is a power of two (`Number.isInteger(Math.log2(b))`).
fn log2_exact(b: u64) -> Option<u32> {
    b.is_power_of_two().then(|| b.trailing_zeros())
}

/// The container class `cls` a transformed collection is stored in.
pub fn container_class(cp: &CollectionPlan, cls: &str) -> Result<String, CompileError> {
    let c = &cp.collection;
    let f = c.fields.len();
    let cols = column_names(&c.fields);
    let params = (0..f).map(|i| format!("v{i}")).collect::<Vec<_>>().join(", ");
    let of_args = (0..f).map(|k| format!("v[i + {k}]")).collect::<Vec<_>>().join(", ");
    let fields = c.fields.join(", ");
    if cp.layout == Layout::Aosoa {
        if c.numeric_fields.len() != c.fields.len() {
            return Err(CompileError(format!("AoSoA needs every field of \"{}\" to be numeric", c.name)));
        }
        let b = cp.block_size;
        let shift = log2_exact(b).ok_or_else(|| CompileError("AoSoA block size must be a power of two".into()))?;
        // Numbers are formatted as JavaScript would print them.
        let n = |x: f64| js_number(x);
        let (bf, ff) = (b as f64, f as f64);
        let stores =
            (0..f).map(|k| format!("this.data[b + {}] = v{k};", n(k as f64 * bf))).collect::<Vec<_>>().join(" ");
        return Ok([
            format!("// Generated by Viscosity: \"{}\" stored as AoSoA, blocks of {} (fields {fields}).", c.name, n(bf)),
            format!("class {cls} {{"),
            format!(
                "  constructor(cap = {}) {{ this.length = 0; this.cap = Math.ceil(cap / {}) * {}; this.data = new Float64Array(this.cap * {f}); }}",
                n(bf * 2.0),
                n(bf),
                n(bf)
            ),
            format!("  static of(...v) {{ const c = new {cls}(v.length / {f}); for (let i = 0; i < v.length; i += {f}) c.push({of_args}); return c; }}"),
            format!(
                "  push({params}) {{ const n = this.length; if (n === this.cap) this.grow(); const b = (n >> {shift}) * {} + (n & {}); {stores} return (this.length = n + 1); }}",
                n(ff * bf),
                n(bf - 1.0)
            ),
            format!("  grow() {{ const d = new Float64Array(this.cap * 2 * {f}); d.set(this.data); this.data = d; this.cap *= 2; }}"),
            "}".to_string(),
        ]
        .join("\n"));
    }
    // Typed columns for numeric fields, plain arrays for the rest.
    let is_typed = |k: usize| c.numeric_fields.contains(&c.fields[k]);
    let typed: Vec<&String> = cols.iter().enumerate().filter(|(k, _)| is_typed(*k)).map(|(_, n)| n).collect();
    let plain: Vec<&String> = cols.iter().enumerate().filter(|(k, _)| !is_typed(*k)).map(|(_, n)| n).collect();
    let typed_init = typed.iter().map(|n| format!("this.{n} = new Float64Array(cap);")).collect::<Vec<_>>().join(" ");
    let plain_init: String = plain.iter().map(|n| format!(" this.{n} = [];")).collect();
    let stores = cols.iter().enumerate().map(|(k, n)| format!("this.{n}[n] = v{k};")).collect::<Vec<_>>().join(" ");
    let grow = typed
        .iter()
        .map(|n| format!("t = new Float64Array(cap); t.set(this.{n}); this.{n} = t;"))
        .collect::<Vec<_>>()
        .join(" ");
    Ok([
        format!("// Generated by Viscosity: \"{}\" stored as a struct of arrays (fields {fields}).", c.name),
        format!("class {cls} {{"),
        format!("  constructor(cap = 16) {{ this.length = 0; this.cap = cap; {typed_init}{plain_init} }}"),
        format!("  static of(...v) {{ const c = new {cls}(Math.max(16, v.length / {f})); for (let i = 0; i < v.length; i += {f}) c.push({of_args}); return c; }}"),
        format!("  push({params}) {{ const n = this.length; if (n === this.cap) this.grow(); {stores} return (this.length = n + 1); }}"),
        format!("  grow() {{ const cap = (this.cap *= 2); let t; {grow} }}"),
        "}".to_string(),
    ]
    .join("\n"))
}

const BOUNDS_HELPER: &str = "// Generated by Viscosity: bounds check matching the original TypeError.
function __vsc_bc(c, i, f, w) {
  if (i >>> 0 === i && i < c.length) return i;
  throw new TypeError(w ? `Cannot set properties of undefined (setting '${f}')` : `Cannot read properties of undefined (reading '${f}')`);
}";

const AOSOA_HELPER: &str =
    "function __vsc_aosoa(i, sh, stride, off, mask) { return (i >> sh) * stride + off + (i & mask); }";

const LATE_HELPER: &str =
    "// Generated by Viscosity: field writes whose right-hand side may throw or run code. The index is
// checked before it runs (__vsc_bk), but the store happens after, into the column as it is then.
let __vsc_k = 0;
function __vsc_bk(c, i) { return i >>> 0 === i && i < c.length ? i : NaN; }
function __vsc_set(c, col, i, v, f) {
  if (i !== i) throw new TypeError(`Cannot set properties of undefined (setting '${f}')`);
  c[col][i] = v;
  return v;
}
function __vsc_seta(c, i, v, f, sh, stride, off, mask) {
  if (i !== i) throw new TypeError(`Cannot set properties of undefined (setting '${f}')`);
  c.data[(i >> sh) * stride + off + (i & mask)] = v;
  return v;
}";

/// Where the operator of an assignment ends (`operatorEnd`): after the
/// target, skip blanks, comments and closing parentheses, then the operator
/// itself and the spaces or tabs after it.
fn operator_end(source: &str, from: u32, op: &str) -> Result<u32, CompileError> {
    let b = source.as_bytes();
    let mut i = from as usize;
    loop {
        let rest = &source[i..];
        match rest.chars().next() {
            Some(c) if is_js_space(c) || c == ')' => i += c.len_utf8(),
            _ if rest.starts_with("//") => {
                i += rest.find(['\n', '\r', '\u{2028}', '\u{2029}']).unwrap_or(rest.len());
            }
            _ if rest.starts_with("/*") => i = rest[2..].find("*/").map_or(source.len(), |e| i + 2 + e + 2),
            _ => break,
        }
    }
    if !source[i..].starts_with(op) {
        return Err(CompileError(format!("internal error: no \"{op}\" after the assignment target at {from}")));
    }
    i += op.len();
    while matches!(b.get(i), Some(b' ' | b'\t')) {
        i += 1;
    }
    Ok(i as u32)
}

/// How an element read from a collection is used.
struct ElementInfo {
    /// Source text of the array expression.
    arr: String,
    /// Source text of the index (or the `for...of` variable).
    idx: String,
    /// The index can be repeated safely (an identifier or a literal).
    simple: bool,
    /// Used directly (`arr[i].x`) rather than through a variable.
    direct: bool,
    /// The `for...of` loop the element comes from, if any.
    for_of: Option<(Span, Span)>,
    /// The index in the source (not for `for...of`).
    span: Option<IndexSpan>,
}

/// The index of `arr[i]` in the source.
#[derive(Copy, Clone, Debug)]
struct IndexSpan {
    span: Span,
    /// A sequence expression, whose span excludes its parentheses.
    seq: bool,
}

/// Stands for the index in a rewritten member, which is then spliced
/// around the index in place, so that the index itself can still be
/// rewritten.
const MARK: &str = "\u{0}";

/// Rewrites `source` according to the plan.
pub fn emit_js(source: &str, module: &Module, nodes: &[JsNode], p: &Plan) -> Result<String, CompileError> {
    let text = |s: Span| &source[s.start as usize..s.end as usize];
    let node_of = |v: ValueId| -> &JsNode {
        let src = module.inst(v).src.expect("rewritten instructions have a source");
        &nodes[src.node.0 as usize]
    };
    let span_of = |v: ValueId| {
        let src = module.inst(v).src.expect("rewritten instructions have a source");
        Span::new(src.start, src.end)
    };

    let mut edits: Vec<Edit> = Vec::new();
    let mut prelude: Vec<String> = Vec::new();
    let mut need_bounds = false;
    let mut need_aosoa = false;
    let mut need_late = false;
    // Field edits keyed by range: a compound assignment (`p.x += 1`) reads
    // and writes the same member, so it would otherwise be edited twice.
    // Keep the read: JavaScript reads `p.x` first, so out of bounds it
    // throws "Cannot read properties of undefined", not "Cannot set". A
    // write that stores late (see LATE_HELPER) covers the read too, so it
    // wins over both: the rank is 0 for a write, 1 for a read, 2 for a late
    // write. (Replacing an entry keeps its position, like a JS `Map`.)
    let mut field_edits: IndexMap<(u32, u32), (Edit, u8, Option<IndexSpan>)> = IndexMap::new();
    let mut field_edit = |e: Edit, rank: u8, idx: Option<IndexSpan>| {
        let key = (e.start, e.end);
        let replace = match field_edits.get(&key) {
            None => true,
            Some((_, prev, _)) => rank > *prev,
        };
        if replace {
            field_edits.insert(key, (e, rank, idx));
        }
    };
    // Replaces an object literal by its values, edit by edit, so that the
    // values themselves can still be rewritten: `{x: a, y: b}` ->
    // `{open}a, b{close}`. A sequence value keeps parentheses (its span
    // excludes them), or its comma would separate arguments.
    let splice_values = |edits: &mut Vec<Edit>, start: u32, end: u32, values: &[Value], open: &str, close: &str| {
        let mut at = start;
        let mut sep = open.to_string();
        for v in values {
            edits.push(Edit::new(at, v.span.start, format!("{sep}{}", if v.is_sequence { "(" } else { "" })));
            at = v.span.end;
            sep = format!("{}, ", if v.is_sequence { ")" } else { "" });
        }
        edits.push(Edit::new(at, end, format!("{}{close}", &sep[..sep.len() - 2])));
    };
    let mut class_names: HashSet<String> = HashSet::default();

    for cp in &p.collections {
        if cp.layout == Layout::Aos {
            continue;
        }
        let c = &cp.collection;
        // Two collections can share a name (in different functions): number them.
        let mut cls = format!("__Vsc_{}", c.name);
        let mut k = 2;
        while class_names.contains(&cls) {
            cls = format!("__Vsc_{}_{k}", c.name);
            k += 1;
        }
        class_names.insert(cls.clone());
        let cols = column_names(&c.fields);
        let field_index = |f: &str| c.fields.iter().position(|x| x == f).expect("a field of the collection");
        prelude.push(container_class(cp, &cls)?);
        let nf = c.fields.len() as f64;
        let b = cp.block_size;
        let mut slot = |arr: &str, f: &str, idx: &str, simple_idx: bool| -> String {
            let k = field_index(f);
            if cp.layout == Layout::Soa {
                return format!("{arr}.{}[{idx}]", cols[k]);
            }
            let sh = log2_exact(b).expect("checked by container_class");
            let bf = b as f64;
            let (stride, off, mask) = (js_number(nf * bf), js_number(k as f64 * bf), js_number(bf - 1.0));
            let at = if simple_idx {
                format!("(({idx}) >> {sh}) * {stride} + {off} + (({idx}) & {mask})")
            } else {
                need_aosoa = true;
                format!("__vsc_aosoa({idx}, {sh}, {stride}, {off}, {mask})")
            };
            format!("{arr}.data[{at}]")
        };

        // 1. Creation.
        let init = span_of(c.init);
        if matches!(module.inst(c.init).op, Op::ArrayEmpty) {
            edits.push(Edit::new(init.start, init.end, format!("new {cls}()")));
        } else {
            let vals: Vec<Value> = c
                .init_records
                .iter()
                .flat_map(|&r| match node_of(r) {
                    JsNode::Object { values } => values.clone(),
                    _ => unreachable!("record.new comes from an object literal"),
                })
                .collect();
            if vals.is_empty() {
                edits.push(Edit::new(init.start, init.end, format!("{cls}.of()")));
            } else {
                splice_values(&mut edits, init.start, init.end, &vals, &format!("{cls}.of("), ")");
            }
        }

        // 2. push({...}) -> push(a, b, ...)
        for &pu in &c.pushes {
            let JsNode::Call { object_arg: Some((arg, values)) } = node_of(pu) else {
                unreachable!("a planned push has an object literal argument")
            };
            if values.is_empty() {
                edits.push(Edit::new(arg.start, arg.end, String::new()));
            } else {
                splice_values(&mut edits, arg.start, arg.end, values, "", "");
            }
        }

        // 3. Elements. Decide, for each index.get, whether it is used
        //    directly (arr[i].x) or through a variable (const p = arr[i]).
        let mut proven: rustc_hash::FxHashMap<ValueId, bool> = Default::default();
        for g in &c.index_gets {
            proven.insert(g.inst, g.bounds_proven); // the last entry wins, like `new Map(...)`
        }
        let mut element_info: IndexMap<ValueId, ElementInfo> = IndexMap::new();
        for g in &c.index_gets {
            let n = span_of(g.inst);
            match node_of(g.inst) {
                JsNode::ForOf { left, right, binding } => {
                    let idx = binding.clone().unwrap_or_else(|| "undefined".into());
                    element_info.insert(
                        g.inst,
                        ElementInfo {
                            arr: text(*right).into(),
                            idx,
                            simple: true,
                            direct: false,
                            for_of: Some((*left, *right)),
                            span: None,
                        },
                    );
                }
                JsNode::Member { object, property, simple_property, sequence_property, direct } => {
                    let span = IndexSpan { span: *property, seq: *sequence_property };
                    element_info.insert(
                        g.inst,
                        ElementInfo {
                            arr: text(*object).into(),
                            idx: text(*property).into(),
                            simple: *simple_property,
                            direct: *direct,
                            for_of: None,
                            span: Some(span),
                        },
                    );
                    if !direct {
                        // The variable now holds the index, not an object.
                        // Keep the index text in place (it may be rewritten
                        // itself); `(a, b)` keeps its parentheses.
                        if *simple_property {
                            edits.push(Edit::new(n.start, n.end, text(*property).into()));
                        } else {
                            let (open, close) = if span.seq { ("(", ")") } else { ("", "") };
                            edits.push(Edit::new(n.start, property.start, open.into()));
                            edits.push(Edit::new(property.end, n.end, close.into()));
                        }
                    }
                }
                _ => unreachable!("index.get comes from a member expression or for...of"),
            }
        }
        for info in element_info.values() {
            if let Some((left, right)) = info.for_of {
                let i = &info.idx;
                edits.push(Edit::new(left.start, right.end, format!("let {i} = 0; {i} < {}.length; {i}++", info.arr)));
            }
        }

        // 4. Field reads and writes.
        for a in &c.accesses {
            // For writes, the source node is the assignment or update; the
            // edit replaces its member expression.
            let (member, object, operator) = match node_of(a.inst) {
                JsNode::Member { object, .. } => (span_of(a.inst), *object, None),
                JsNode::Write { member, object, operator } => (*member, *object, operator.as_deref()),
                _ => unreachable!("field accesses come from member expressions"),
            };
            let info = &element_info[&a.element];
            let ok = proven[&a.element] || p.options.bounds == Bounds::Assume;
            let write = a.kind == AccessKind::Write;
            // A write that must store after its right-hand side runs: a
            // typed column may be replaced (grown) meanwhile, and an index
            // out of bounds must throw only after the right-hand side ran,
            // as in the original.
            let typed = cp.layout == Layout::Aosoa || c.numeric_fields.contains(&a.field);
            if let Some(op) = operator.filter(|&op| {
                write && ((op == "=" && !ok && a.rhs != RhsEffect::Inert) || (typed && a.rhs == RhsEffect::Effects))
            }) {
                let raw = if info.direct { MARK.to_string() } else { text(object).to_string() };
                let k = field_index(&a.field);
                let arr = &info.arr;
                let set = |i: &str| match cp.layout {
                    Layout::Soa => format!("__vsc_set({arr}, '{}', {i}", cols[k]),
                    _ => format!("__vsc_seta({arr}, {i}"),
                };
                let tail = match cp.layout {
                    Layout::Soa => format!(", '{}')", a.field),
                    _ => {
                        let sh = log2_exact(b).expect("checked by container_class");
                        let bf = b as f64;
                        let (stride, off, mask) = (js_number(nf * bf), js_number(k as f64 * bf), js_number(bf - 1.0));
                        format!(", '{}', {sh}, {stride}, {off}, {mask})", a.field)
                    }
                };
                let (head, op_text, close) = if op == "=" {
                    let i = if ok { raw } else { format!("__vsc_bk({arr}, {raw})") };
                    (set(&i), ", ".to_string(), tail)
                } else {
                    let idx = if ok { raw } else { format!("__vsc_bc({arr}, {raw}, '{}', false)", a.field) };
                    if !ok {
                        need_bounds = true;
                    }
                    let old = slot(arr, &a.field, "__vsc_k", true);
                    let bin = &op[..op.len() - 1];
                    if matches!(bin, "&&" | "||" | "??") {
                        (
                            format!("(__vsc_k = {idx}, {old} {bin} {}", set("__vsc_k")),
                            ", ".to_string(),
                            format!("{tail})"),
                        )
                    } else {
                        (
                            format!("{}, {old}", set(&format!("__vsc_k = {idx}"))),
                            format!(" {bin} ("),
                            format!("){tail}"),
                        )
                    }
                };
                need_late = true;
                let end = span_of(a.inst);
                field_edit(Edit::new(member.start, member.end, head), 2, info.span);
                edits.push(Edit::new(member.end, operator_end(source, member.end, op)?, op_text));
                edits.push(Edit { start: end.end, end: end.end, text: close, rank: end.start });
                continue;
            }
            let mut idx = if info.direct { MARK.to_string() } else { text(object).to_string() };
            if !ok {
                idx = format!("__vsc_bc({}, {idx}, '{}', {write})", info.arr, a.field);
                need_bounds = true;
            }
            let simple = if info.direct { info.simple && ok } else { ok };
            let t = slot(&info.arr, &a.field, &idx, simple);
            let span = if info.direct { info.span } else { None };
            field_edit(Edit::new(member.start, member.end, t), if write { 0 } else { 1 }, span);
        }
    }
    if prelude.is_empty() {
        return Ok(source.to_string());
    }
    for (e, _, idx) in field_edits.into_values() {
        let parts: Vec<&str> = e.text.split(MARK).collect();
        match idx {
            Some(idx) if parts.len() > 2 => {
                // A simple index (an identifier or a literal) may be repeated.
                let text = parts.join(&source[idx.span.start as usize..idx.span.end as usize]);
                edits.push(Edit { text, ..e });
            }
            Some(idx) if parts.len() == 2 => {
                let (open, close) = if idx.seq { ("(", ")") } else { ("", "") };
                edits.push(Edit::new(e.start, idx.span.start, format!("{}{open}", parts[0])));
                edits.push(Edit::new(idx.span.end, e.end, format!("{close}{}", parts[1])));
            }
            _ => edits.push(e),
        }
    }
    if need_bounds {
        prelude.push(BOUNDS_HELPER.into());
    }
    if need_aosoa {
        prelude.push(AOSOA_HELPER.into());
    }
    if need_late {
        prelude.push(LATE_HELPER.into());
    }

    // Apply edits back to front; overlapping edits would mean a bug. At one
    // position, a replacement goes before an insertion (it ends later), and
    // of two insertions the one closing the outer assignment (smaller rank)
    // first, so that it ends up after the inner one. (Stable, like
    // Array.prototype.sort.)
    edits.sort_by_key(|e| (std::cmp::Reverse(e.start), std::cmp::Reverse(e.end), e.rank));
    let mut out = source.to_string();
    let mut last_start = u32::MAX;
    for e in &edits {
        if e.end > last_start {
            return Err(CompileError(format!("internal error: overlapping rewrites at {}-{}", e.start, e.end)));
        }
        out.replace_range(e.start as usize..e.end as usize, &e.text);
        last_start = e.start;
    }
    // The prelude goes after any shebang and leading "use strict" directive.
    let head = prelude_position(&out);
    Ok(format!("{}{}\n{}", &out[..head], prelude.join("\n"), &out[head..]))
}

/// JavaScript's `\s`.
pub fn is_js_space(c: char) -> bool {
    matches!(
        c,
        '\t' | '\n' | '\u{b}' | '\u{c}' | '\r' | ' ' | '\u{a0}' | '\u{1680}' | '\u{2000}'
            ..='\u{200a}' | '\u{2028}' | '\u{2029}' | '\u{202f}' | '\u{205f}' | '\u{3000}' | '\u{feff}'
    )
}

/// The length of the match of `/^(#![^\n]*\n)?(\s*(['"])use strict\3;?\s*\n)?/`
/// in `s`: where the prelude goes.
fn prelude_position(s: &str) -> usize {
    let mut pos = 0;
    if s.starts_with("#!") {
        if let Some(nl) = s.find('\n') {
            pos = nl + 1;
        }
    }
    let rest = &s[pos..];
    let ws = rest.len() - rest.trim_start_matches(is_js_space).len();
    let after = &rest[ws..];
    let Some(quote) = after.chars().next().filter(|c| *c == '\'' || *c == '"') else {
        return pos;
    };
    let directive = format!("{quote}use strict{quote}");
    let Some(tail) = after.strip_prefix(directive.as_str()) else {
        return pos;
    };
    let tail = tail.strip_prefix(';').unwrap_or(tail);
    // `\s*\n`: the whitespace run up to (and including) its last newline.
    let run_len = tail.len() - tail.trim_start_matches(is_js_space).len();
    match tail[..run_len].rfind('\n') {
        Some(nl) => s.len() - tail.len() + nl + 1,
        None => pos,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn column_name_rules() {
        assert_eq!(column_name("x", 0), "x");
        assert_eq!(column_name("$a_1", 0), "$a_1");
        assert_eq!(column_name("length", 2), "f2_");
        assert_eq!(column_name("a-b", 1), "f1_");
        assert_eq!(column_name("1a", 3), "f3_");
        assert_eq!(column_name("é", 0), "f0_");
    }

    #[test]
    fn renamed_columns_never_clash() {
        let fields: Vec<String> = ["length", "f0_", "f0__", "x"].iter().map(|s| s.to_string()).collect();
        assert_eq!(column_names(&fields), vec!["f0___", "f0_", "f0__", "x"]);
        let fields: Vec<String> = ["a-b", "c-d"].iter().map(|s| s.to_string()).collect();
        assert_eq!(column_names(&fields), vec!["f0_", "f1_"]);
    }

    #[test]
    fn prelude_goes_after_directives() {
        assert_eq!(prelude_position("const a = 1;\n"), 0);
        assert_eq!(prelude_position("#!/usr/bin/env node\nx"), 20);
        assert_eq!(prelude_position("'use strict';\nx"), 14);
        assert_eq!(prelude_position("#!node\n\n\"use strict\"  \n\n  x"), 24);
        assert_eq!(prelude_position("'use strict'; x"), 0);
        assert_eq!(prelude_position("#!node"), 0);
    }
}
